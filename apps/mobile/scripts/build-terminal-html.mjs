// Inlines xterm.js into one HTML page for the native terminal WebView, which cannot load node_modules.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const read = (specifier) => readFileSync(require.resolve(specifier), "utf8")
const inlineScript = (source) => source.replaceAll("</script", "<\\/script")

const page = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${read("@xterm/xterm/css/xterm.css")}
html, body, #terminal { margin: 0; height: 100%; width: 100%; overflow: hidden; }
body { background: var(--kk-background, #0a0a0a); }
#terminal { box-sizing: border-box; padding: 6px; }
</style>
</head>
<body>
<div id="terminal"></div>
<script>${inlineScript(read("@xterm/xterm/lib/xterm.js"))}</script>
<script>${inlineScript(read("@xterm/addon-fit/lib/addon-fit.js"))}</script>
<script>
const theme = window.kkTheme || {}
document.body.style.setProperty("--kk-background", theme.background || "#0a0a0a")
const term = new Terminal({ fontSize: 13, fontFamily: "Menlo, monospace", cursorBlink: true, scrollback: 5000, theme })
const fit = new FitAddon.FitAddon()
term.loadAddon(fit)
term.open(document.getElementById("terminal"))
// xterm already turns autocorrect and autocapitalize off. Android keyboards still suggest and
// rewrite words until the field also says autocomplete off, which Chromium maps to NO_SUGGESTIONS.
term.textarea.setAttribute("autocomplete", "off")
const post = (message) => window.ReactNativeWebView.postMessage(JSON.stringify(message))
let size = ""
const resize = () => {
  fit.fit()
  if (!(term.cols > 0 && term.rows > 0) || size === term.cols + "x" + term.rows) return
  size = term.cols + "x" + term.rows
  post({ type: "size", cols: term.cols, rows: term.rows })
}
new ResizeObserver(resize).observe(document.body)
resize()
term.onData((data) => post({ type: "input", data }))
let applicationCursor = false
term.onWriteParsed(() => {
  if (term.modes.applicationCursorKeysMode === applicationCursor) return
  applicationCursor = term.modes.applicationCursorKeysMode
  post({ type: "cursorMode", applicationCursor })
})
window.kkWrite = (data) => term.write(data)
</script>
</body>
</html>
`

const out = new URL("../src/terminal/terminal-page.ts", import.meta.url)
writeFileSync(
  out,
  `// Generated by scripts/build-terminal-html.mjs from @xterm/xterm. Run \`pnpm build:terminal\` after upgrading it.\nexport const TERMINAL_HTML = ${JSON.stringify(page)}\n`,
)
