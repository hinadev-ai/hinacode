import { encodeTar, type TarEntry } from "../tar.ts"

export const EXTENSION_DIR = "passkey-extension"

const MANIFEST = JSON.stringify(
  {
    manifest_version: 3,
    name: "HinaCode VM passkey relay",
    version: "1.0",
    permissions: ["webAuthenticationProxy", "tabs"],
    host_permissions: ["*://*/*"],
    background: { service_worker: "background.js" },
    content_scripts: [
      { matches: ["*://*/*"], js: ["page.js"], run_at: "document_start", all_frames: true, world: "MAIN" },
      { matches: ["*://*/*"], js: ["content.js"], run_at: "document_start", all_frames: true },
    ],
  },
  null,
  2,
)

const PAGE = [
  "if (!window.__hinacodePasskeyWrapped && navigator.credentials) {",
  "  window.__hinacodePasskeyWrapped = true",
  "  const encode = (value) => {",
  "    if (typeof value === 'string') return value",
  "    if (!value) return ''",
  "    const bytes = value instanceof ArrayBuffer ? new Uint8Array(value) : new Uint8Array(value.buffer, value.byteOffset || 0, value.byteLength)",
  "    let binary = ''",
  "    bytes.forEach((byte) => { binary += String.fromCharCode(byte) })",
  "    return btoa(binary).replace(/\\+/g, '-').replace(/\\//g, '_').replace(/=+$/, '')",
  "  }",
  "  const wrap = (kind) => {",
  "    const original = navigator.credentials[kind]",
  "    if (typeof original !== 'function') return",
  "    navigator.credentials[kind] = function (options) {",
  "      const publicKey = options && options.publicKey",
  "      if (publicKey) {",
  "        window.postMessage({",
  "          __hinacodePasskey: {",
  "            kind: kind === 'get' ? 'get' : 'create',",
  "            origin: location.origin,",
  "            top: window.top === window,",
  "            challenge: encode(publicKey.challenge),",
  "          },",
  "        }, '*')",
  "      }",
  "      return original.call(navigator.credentials, options)",
  "    }",
  "  }",
  "  wrap('get')",
  "  wrap('create')",
  "}",
].join("\n")

const CONTENT = [
  "window.addEventListener('message', (event) => {",
  "  if (event.source !== window) return",
  "  const record = event.data && event.data.__hinacodePasskey",
  "  if (!record) return",
  "  chrome.runtime.sendMessage({ type: 'hinacode-origin', record }).catch(() => {})",
  "})",
].join("\n")

const BACKGROUND = [
  "const seen = new Map()",
  "const timers = new Map()",
  "let armed = false",
  "",
  "chrome.runtime.onMessage.addListener((message) => {",
  "  if (!message || message.type !== 'hinacode-origin' || !message.record) return",
  "  seen.set(message.record.challenge, message.record)",
  "  setTimeout(() => seen.delete(message.record.challenge), 300000)",
  "})",
  "",
  "const notify = (payload) => {",
  "  const binding = globalThis.__hinacodePasskeyRequest",
  "  if (typeof binding !== 'function') return false",
  "  binding(JSON.stringify(payload))",
  "  return true",
  "}",
  "",
  "const fail = (kind, requestId, message) => {",
  "  const details = { requestId, error: { name: 'NotAllowedError', message } }",
  "  if (kind === 'get') chrome.webAuthenticationProxy.completeGetRequest(details)",
  "  else chrome.webAuthenticationProxy.completeCreateRequest(details)",
  "}",
  "",
  "const waitRecord = async (challenge) => {",
  "  for (let attempt = 0; attempt < 40; attempt++) {",
  "    const record = seen.get(challenge)",
  "    if (record) return record",
  "    await new Promise((resolve) => setTimeout(resolve, 50))",
  "  }",
  "  try {",
  "    const [tab] = await chrome.tabs.query({ active: true, lastFocusedWindow: true })",
  "    if (tab && tab.url) return { origin: new URL(tab.url).origin, top: true }",
  "  } catch {}",
  "  return undefined",
  "}",
  "",
  "const handle = (kind) => async (info) => {",
  "  let details",
  "  try { details = JSON.parse(info.requestDetailsJson) } catch {",
  "    fail(kind, info.requestId, 'HinaCode could not read this passkey request')",
  "    return",
  "  }",
  "  const record = await waitRecord(details.challenge)",
  "  if (!record || !record.top) {",
  "    fail(kind, info.requestId, 'HinaCode passkeys only run for top level pages in the VM')",
  "    return",
  "  }",
  "  const sent = notify({",
  "    type: 'request',",
  "    kind,",
  "    requestId: info.requestId,",
  "    requestDetailsJson: info.requestDetailsJson,",
  "    origin: record.origin,",
  "  })",
  "  if (!sent) {",
  "    fail(kind, info.requestId, 'The passkey relay to this Mac is not connected')",
  "    return",
  "  }",
  "  const timeout = Math.min(Math.max(details.timeout || 120000, 15000), 180000)",
  "  timers.set(info.requestId, setTimeout(() => {",
  "    timers.delete(info.requestId)",
  "    fail(kind, info.requestId, 'No answer came from this Mac in time')",
  "    notify({ type: 'timeout', requestId: info.requestId })",
  "  }, timeout))",
  "}",
  "",
  "chrome.webAuthenticationProxy.onGetRequest.addListener(handle('get'))",
  "chrome.webAuthenticationProxy.onCreateRequest.addListener(handle('create'))",
  "chrome.webAuthenticationProxy.onIsUvpaaRequest.addListener((info) => {",
  "  chrome.webAuthenticationProxy.completeIsUvpaaRequest({ requestId: info.requestId, isUvpaa: armed })",
  "})",
  "chrome.webAuthenticationProxy.onRequestCanceled.addListener((requestId) => {",
  "  const timer = timers.get(requestId)",
  "  if (timer) clearTimeout(timer)",
  "  timers.delete(requestId)",
  "  notify({ type: 'canceled', requestId })",
  "})",
  "",
  "globalThis.__hinacodeArm = async () => {",
  "  if (!armed) {",
  "    await chrome.webAuthenticationProxy.attach()",
  "    armed = true",
  "  }",
  "  return armed",
  "}",
  "",
  "globalThis.__hinacodeDisarm = async () => {",
  "  if (armed) {",
  "    await chrome.webAuthenticationProxy.detach()",
  "    armed = false",
  "  }",
  "  return armed",
  "}",
  "",
  "globalThis.__hinacodeComplete = (json) => {",
  "  const { kind, requestId, responseJson, error } = JSON.parse(json)",
  "  const timer = timers.get(requestId)",
  "  if (timer) clearTimeout(timer)",
  "  timers.delete(requestId)",
  "  const details = error ? { requestId, error } : { requestId, responseJson }",
  "  if (kind === 'get') chrome.webAuthenticationProxy.completeGetRequest(details)",
  "  else chrome.webAuthenticationProxy.completeCreateRequest(details)",
  "}",
].join("\n")

const file = (name: string, contents: string): TarEntry => ({
  type: "file",
  path: `${EXTENSION_DIR}/${name}`,
  data: new TextEncoder().encode(contents),
  mode: 0o644,
  mtime: 0,
})

export const extensionArchive = (): Uint8Array =>
  encodeTar([
    { type: "dir", path: EXTENSION_DIR, mode: 0o755, mtime: 0 },
    file("manifest.json", MANIFEST),
    file("background.js", BACKGROUND),
    file("content.js", CONTENT),
    file("page.js", PAGE),
  ])
